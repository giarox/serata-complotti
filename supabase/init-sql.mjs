// Builds the one-off private SQL that fills the Supabase project created by setup.sql.
// Passwords are hashed locally with the same pgcrypto bcrypt used by Supabase,
// so the plain passwords never reach Supabase or its query logs.
import { PGlite } from '@electric-sql/pglite';
import { pgcrypto } from '@electric-sql/pglite/contrib/pgcrypto';

export const defaultSettings = () => ({
  maxAwards: null,
  awardOrder: ['credibility', 'delivery', 'research', 'supercazzola'],
  spectatorsVote: true,
});

export async function hashPasswords(...passwords) {
  const db = await PGlite.create({ extensions: { pgcrypto } });
  await db.exec('create extension if not exists pgcrypto;');
  const hashes = [];
  for (const pw of passwords) {
    const { rows } = await db.query("select crypt($1, gen_salt('bf', 10)) as h", [pw]);
    hashes.push(rows[0].h);
  }
  await db.close();
  return hashes;
}

export function validateRoster(roster) {
  if (!Array.isArray(roster) || roster.length === 0)
    throw new Error('roster.json deve contenere una lista di persone.');
  const ids = new Set();
  for (const p of roster) {
    for (const k of ['id', 'name', 'role'])
      if (typeof p[k] !== 'string' || !p[k].trim()) throw new Error(`Manca "${k}" in ${JSON.stringify(p)}`);
    if (typeof p.spectator !== 'boolean') throw new Error(`"spectator" deve essere true o false per ${p.name}`);
    if (!p.spectator && !String(p.title ?? '').trim()) throw new Error(`Manca il titolo del talk per ${p.name}`);
    if (p.deckUrl && !/^https:\/\/docs\.google\.com\/presentation\//.test(p.deckUrl))
      throw new Error(`Link Slides non valido per ${p.name}`);
    if (ids.has(p.id)) throw new Error(`id duplicato: ${p.id}`);
    ids.add(p.id);
  }
  return roster.map((p) => ({
    id: p.id,
    name: p.name,
    role: p.role,
    title: p.title ?? '',
    deckUrl: p.deckUrl ?? '',
    spectator: p.spectator,
  }));
}

const literal = (value) => `'${String(value).replaceAll("'", "''")}'`;

/**
 * reset=false: if the event already exists, only the passwords change (names, rounds and votes are kept).
 * reset=true: replaces the whole event with a clean one and disconnects every phone.
 */
export function buildInitSql({ guestHash, gmHash, roster, reset = false }) {
  const state = {
    phase: 'waiting',
    activeRoundId: null,
    participants: roster,
    rounds: [],
    votes: [],
    revealed: 0,
    revision: 0,
    settings: defaultSettings(),
  };
  return `-- PRIVATE: generated by npm run make-init. Run once in the Supabase SQL editor, then delete this file.
-- Contains only password hashes, never the passwords themselves.
begin;
${reset ? 'delete from public.party_members;\n' : ''}insert into public.party_store(id, state, guest_hash, gm_hash)
values (true, ${literal(JSON.stringify(state))}::jsonb, ${literal(guestHash)}, ${literal(gmHash)})
on conflict (id) do update set
  guest_hash = excluded.guest_hash,
  gm_hash = excluded.gm_hash${reset ? ',\n  state = excluded.state' : ''};
update public.party_signal set revision = revision + 1 where id = true;
commit;
`;
}
